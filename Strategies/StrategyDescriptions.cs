        public static TimeframeSettings GetSettings(string timeframe)
        {
            var normalizedTimeframe = timeframe?.ToLower().Replace(" ", "") ?? "5min";

            return _settings.TryGetValue(normalizedTimeframe, out var settings)
                ? settings
                : _settings["5min"];
        }

        public static void ApplySettingsToViewModel(MaSettingsViewModel viewModel, string timeframe)
        {
            var settings = GetSettings(timeframe);

            // ✅ Добавляем третий параметр - FilterSmaPeriod
            // Используем значение по умолчанию 20, либо можно вычислить из настроек
            int filterSmaPeriod = 20; // Можно вычислить из settings.SmaPeriods

            // Парсим SMA периоды и берем средний как фильтр
            var smaPeriods = settings.SmaPeriods
                .Split(',', StringSplitOptions.RemoveEmptyEntries)
                .Select(p => int.Parse(p.Trim()))
                .ToList();

            if (smaPeriods.Count >= 2)
            {
                // Берем средний SMA период как фильтр
                filterSmaPeriod = smaPeriods[smaPeriods.Count / 2];
            }

            // ✅ Сбрасываем флаг ручного режима при установке оптимальных параметров
            viewModel.UseManualFilterSma = false;
            viewModel.SetOptimalParameters(settings.SmaPeriods, settings.EmaPeriods, filterSmaPeriod);
        }
